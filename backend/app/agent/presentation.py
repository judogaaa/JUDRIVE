"""Conservative presentation boundary for untrusted model text.

Only evidence returned by the tools for this turn may become a citation.
This is not a semantic proof of mechanical correctness.
"""
from __future__ import annotations

import re
from typing import Any

_ID = r"[a-z][a-z0-9-]*:p\d{1,6}"
_CITATION = re.compile(rf"(?:\[({_ID})\]|(?<![\w:-])({_ID})(?![\w:-]))", re.IGNORECASE)
_MARKDOWN_LINK = re.compile(r"\[([^\]\n]{1,500})\]\([^\n)]{1,1000}\)")
_URL = re.compile(r"(?:https?://|javascript:|data:)[^\s<>]+", re.IGNORECASE)


def format_answer(text: str, sources: list[dict[str, Any]]) -> tuple[str, list[dict[str, Any]]]:
    """Normalize known citations, discard model-generated URLs and reject unknown IDs.

    Empty output signals that the orchestrator must use its localized fallback.
    Preserve actual sources for browsing even if the model's synthesis is rejected.
    """
    known = {str(row["evidence_id"]): row for row in sources if row.get("evidence_id")}
    result = (text or "").strip()
    if not result or result.startswith("{") or any(marker in result for marker in ("```", "Traceback (", "httpx.HTTPStatusError", "tool_calls")):
        return "", list(known.values())
    # A label may be useful; the destination generated by LLM never is.
    result = _MARKDOWN_LINK.sub(lambda match: match.group(1), result)
    result = _URL.sub("", result)
    cited: list[str] = []
    invalid = False

    def replace(match: re.Match[str]) -> str:
        nonlocal invalid
        eid = match.group(1) or match.group(2)
        if eid not in known:
            invalid = True
            return ""
        if eid not in cited:
            cited.append(eid)
        return f"[{eid}]"

    result = _CITATION.sub(replace, result).strip()
    ordered = [known[eid] for eid in cited] + [known[eid] for eid in known if eid not in cited]
    return ("" if invalid else result), ordered
